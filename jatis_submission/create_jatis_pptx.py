def build_pptx():
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    # Slide 1: Gap map (editable shapes)
    _slide_gapmap(prs)

    # Slide 2: Pipeline (editable shapes)
    _slide_pipeline(prs)

    # Slides 3–7: data figures (embedded PNGs)
    for fig in IMAGE_FIGURES:
        _slide_image(prs, fig)

    out_path = OUT_DIR / 'figures_jatis.pptx'
    prs.save(str(out_path))
    print(f"PPTX saved: {out_path}")


if __name__ == '__main__':
    build_pptx()
