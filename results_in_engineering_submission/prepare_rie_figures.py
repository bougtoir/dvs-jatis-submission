"""Compose final, manuscript-number-aligned figures for the RIE submission.

The script assumes source PNG/TIFF files have already been generated by:
    python generate_sr_figures.py
    python ../noise_inverse_demo.py
    python ../systematic_evaluation.py
    python ../create_figures_en_pptx.py

Outputs are placed in results_in_engineering_submission/rie_figures/:
    fig1_schematic.png
    fig2_optimal_rho.png
    fig3_pipeline_en.png
    fig4_sr_curves.png
    fig5_detection_and_roc.png
    fig6_a5_simulation.png
    fig7_evaluation_and_application.png
    fig8_proof_of_concept.png
    supplementary_fig_per_recording.png/tiff
"""
from pathlib import Path
from PIL import Image
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from utils import DPI

SCRIPT_DIR = Path(__file__).resolve().parent
OUT_DIR = SCRIPT_DIR / 'rie_figures'
OUT_DIR.mkdir(exist_ok=True)

SR_DIR = SCRIPT_DIR / 'sr_figures'
ROOT_DIR = SCRIPT_DIR.parent  # dvs_noise_inverse_problem/


def save_both(img, path_stem: Path):
    """Save image as PNG and TIFF-LZW at 600 dpi."""
    png_path = OUT_DIR / f'{path_stem}.png'
    tiff_path = OUT_DIR / f'{path_stem}.tiff'
    img.save(png_path, dpi=(DPI, DPI))
    img.save(tiff_path, compression='tiff_lzw', dpi=(DPI, DPI))
    print(f'  -> {png_path.name} + {tiff_path.name}')


def load_img(path):
    if not path.exists():
        raise FileNotFoundError(path)
    return Image.open(path).convert('RGB')


def copy_to_rie(name, src):
    img = load_img(src)
    save_both(img, Path(name))
    return img


def stack(name, *srcs):
    """Vertically stack images on a common canvas.

    Narrower images are padded with white on the left/right so they are never
    upscaled; wider images are downsampled to the maximum width of the others.
    This preserves text/DPI quality in the final combined figure.
    """
    imgs = [load_img(s) for s in srcs]
    target_w = max(img.width for img in imgs)
    resized = []
    for img in imgs:
        if img.width < target_w:
            # Pad with white, centred, to avoid upscaling.
            padded = Image.new('RGB', (target_w, img.height), 'white')
            x_offset = (target_w - img.width) // 2
            padded.paste(img, (x_offset, 0))
            img = padded
        elif img.width > target_w:
            ratio = target_w / img.width
            new_h = int(img.height * ratio)
            img = img.resize((target_w, new_h), Image.Resampling.LANCZOS)
        resized.append(img)
    total_h = sum(img.height for img in resized)
    canvas = Image.new('RGB', (target_w, total_h), 'white')
    y = 0
    for img in resized:
        canvas.paste(img, (0, y))
        y += img.height
    save_both(canvas, Path(name))


def main():
    print('Preparing RIE-aligned figures...')

    # Non-combined, filename-aligned figures.
    copy_to_rie('fig1_schematic', SR_DIR / 'fig1_schematic.png')
    copy_to_rie('fig2_optimal_rho', SR_DIR / 'fig3_optimal_rho.png')
    copy_to_rie('fig3_pipeline_en', ROOT_DIR / 'fig2_g3_pipeline_en.png')
    copy_to_rie('fig4_sr_curves', SR_DIR / 'fig2_sr_curves.png')
    copy_to_rie('fig6_a5_simulation', ROOT_DIR / 'fig6_a5_simulation.png')

    # Combined figures.
    stack('fig5_detection_and_roc',
          SR_DIR / 'fig4_detection_probability.png',
          SR_DIR / 'fig5_roc_comparison.png')

    stack('fig7_evaluation_and_application',
          ROOT_DIR / 'fig5_systematic_evaluation.png',
          SR_DIR / 'fig7_dvs_application.png')

    stack('fig8_proof_of_concept',
          ROOT_DIR / 'fig3_noise_inverse_demo.png',
          ROOT_DIR / 'fig4_sn_improvement_rie.png')

    # Supplementary material figure.
    copy_to_rie('supplementary_fig_per_recording',
                ROOT_DIR / 'fig7_per_recording_comparison.png')

    print('RIE figure preparation complete.')


if __name__ == '__main__':
    main()
